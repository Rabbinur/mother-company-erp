import { NextRequest } from "next/server";
import { connectDB } from "@/lib/db/connect";
import { requireAuth } from "@/lib/auth/session";
import { DispatchService } from "@/services/DispatchService";
import {
  successResponse,
  errorResponse,
  unauthorizedResponse,
} from "@/lib/utils/api-response";

export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const user = await requireAuth(req);
  if (!user) return unauthorizedResponse();

  const { id } = await params;
  let body: any = {};
  try {
    body = await req.json();
  } catch {
    // optional body
  }

  await connectDB();

  try {
    const dispatch = await DispatchService.cancelDispatch(id, body.reason, user.userId);
    return successResponse(dispatch, "Dispatch trip cancelled and in-transit stock restored");
  } catch (err: any) {
    return errorResponse(err.message || "Failed to cancel dispatch", 400);
  }
}
